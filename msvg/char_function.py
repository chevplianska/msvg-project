"""Market-implied characteristic function, and calibration in CF space.

Carr-Madan's out-of-the-money transform inverts algebraically. Writing
``y = log(S_T/F)`` for the forward-normalized log return, ``k = log(K/F)``,
and ``z(k)`` for the forward-normalized OTM option price (put below the
forward, call above it),

.. math::

    \\zeta(v) = \\int e^{ivk} z(k)\\,dk
             = \\frac{1 - \\varphi(v - i)}{v^2 - iv}
    \\qquad\\Longleftrightarrow\\qquad
    \\varphi(v - i) = 1 + iv(1 + iv)\\,\\zeta(v).

So the quoted chain *determines* the risk-neutral characteristic function on
the line ``Im(u) = -1``, in closed form, with

* no damping parameter ``alpha`` and therefore no implicit strike reweighting,
* no interpolation of quotes onto a continuum,
* no numerical inversion of anything.

Two structural consequences drive this module.

**The martingale condition is free.** At ``v = 0`` the identity forces
``phi(-i) = 1`` regardless of the quotes, because the prefactor vanishes. What
is imposed as a constraint elsewhere is an algebraic identity here.

**The transform is linear**, so the BBO box ``{z_j in [b_j, a_j]}`` has an
*exact* image at each frequency: a zonotope in the complex plane, centred on
the mid and generated by the half-spreads (:func:`cf_zonotope`). "The model is
inside the quoted market" is therefore an exact convex condition. None of the
machinery the implied-volatility loss required -- nonlinear inversion, a
fallback penalty for uninvertible prices, a vol-width normalization -- appears,
and neither does the escape hatch that fallback opened (see the protocol doc,
section 11.4).

Consistency with the production objective is exact, not approximate:

* implied volatility is strictly increasing in price, so the IV band and the
  price band have the *same* zero set -- verified at 0 disagreements over
  540,690 strike-model tests;
* on a Nyquist-complete frequency grid (:func:`nyquist_vmax`) the operator
  ``phi = 1 + M z`` is a bijection, so the price box pulls back to CF space
  with no relaxation -- verified at 0 mismatches over 132,459 strike-tests,
  round-trip error 2e-15.

The grid requirement is the one real trap. Resolving the *finest strike
spacing* needs ``v_max ~ pi / min(diff(k))``, which is far beyond what the
k-span alone suggests: on the 2026-08-10 SPXW chain, ``2 pi n / span`` gives
2178 and leaves the operator rank 164 of 201, while the correct 12452 gives
full rank at condition number 130. Undersample and the CF band condition
silently becomes a *strict relaxation* of the price box -- a model can look
inside in CF space while its prices sit outside the quotes.

**Score the model through the same operator, never against the exact CF.**
The tempting shortcut is to compare :func:`model_cf`, which is closed form and
13-23x cheaper than pricing, directly against the market zonotope. On a real
chain that is wrong. The trapezoid rule tracks the continuous transform only
while ``e^{ivk}`` is resolved, ``v << pi / max(diff(k))``, but the operator is
injective only for ``v >~ pi / min(diff(k))``. SPXW quotes 5-point strikes at
the money and 200-point strikes in the wings, so those thresholds sit at 90 and
4981 -- a factor of 56 apart, with no overlap. At ``v = 50`` the discrete
transform already carries 24% relative error, and MSVG scores 159.6 against the
exact CF where the priced route gives 1.35. Restricting to a uniformly spaced
strike run does merge the two regimes, but such a run covers only the dense
at-the-money region, where ``z`` has not decayed and truncation replaces
aliasing. Both routes are available; only the priced one is faithful.
"""

