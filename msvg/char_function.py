def share_measure_bounds(k, z_bid, z_ask, tau):
    """Exact model-free interval for the share-measure moments of ``y``.

    Because ``phi(v - i)`` is the characteristic function of ``y`` under the
    share measure, its low-order Taylor coefficients are *linear* functionals
    of ``z``. Expanding ``iv(1 + iv)e^{ivk} = iv - v^2(k + 1) + O(v^3)``,

        phi(v - i) = 1 + i v S_0 - v^2 S_1 + O(v^3),
        S_0 = sum_j w_j z_j,   S_1 = sum_j w_j (k_j + 1) z_j,

    so each has an exact interval over the quote box, attained at a vertex --
    no optimization, no model. This is the tightest statement the quotes make
    on their own, and any admissible model must land inside it.
    """
    k = np.asarray(k, float)
    w = trapezoid_weights(k)
    z_bid, z_ask = np.asarray(z_bid, float), np.asarray(z_ask, float)
    centre, radius = 0.5 * (z_bid + z_ask), 0.5 * np.abs(z_ask - z_bid)
    s0_c, s0_r = float(w @ centre), float(np.abs(w) @ radius)
    s1_c, s1_r = float((w * (k + 1)) @ centre), float(np.abs(w * (k + 1)) @ radius)
    m2_lo, m2_hi = 2.0 * (s1_c - s1_r), 2.0 * (s1_c + s1_r)
    sd_lo = np.sqrt(max(m2_lo - (s0_c + s0_r) ** 2, 0.0))
    sd_hi = np.sqrt(max(m2_hi - (s0_c - s0_r) ** 2, 0.0))
    return {
        "mean": (s0_c - s0_r, s0_c + s0_r),
        "second_moment": (m2_lo, m2_hi),
        "sd": (sd_lo, sd_hi),
        "sd_annualized": (sd_lo / np.sqrt(tau), sd_hi / np.sqrt(tau)),
    }
