# --------------------------------------------------------------------------
# Market side: quotes -> characteristic function
# --------------------------------------------------------------------------
def otm_from_surface(surface, D_hat, A_hat, F_hat, strikes=None):
    """Forward-normalized OTM prices ``z(k)`` from the call-equivalent surface.

    ``surface`` carries call-equivalent BBO at every strike. Out-of-the-money
    means the put below the forward and the call above it; the put is recovered
    through the same parity relation that built the surface, so no new carry
    assumption enters. Returns ``(k, {side: z}, strikes)`` sorted by ``k``.
    """
    K = surface["strike"].to_numpy(float)
    if strikes is not None:
        keep = np.isin(K, np.asarray(strikes, float))
        surface, K = surface.loc[keep], K[keep]
    out = {}
    for side in ("bid", "ask", "mid"):
        call = surface[side].to_numpy(float)
        put = call - A_hat + D_hat * K
        out[side] = np.where(K >= F_hat, call, put) / (D_hat * F_hat)
    k = np.log(K / F_hat)
    order = np.argsort(k)
    return k[order], {s: v[order] for s, v in out.items()}, K[order]


def trapezoid_weights(k):
    """Quadrature weights for a possibly non-uniform ``k`` grid."""
    k = np.asarray(k, float)
    w = np.empty_like(k)
    w[1:-1] = 0.5 * (k[2:] - k[:-2])
    w[0] = 0.5 * (k[1] - k[0])
    w[-1] = 0.5 * (k[-1] - k[-2])
    return w


def cf_operator(k, v):
    """Complex matrix ``M`` with ``phi = 1 + M @ z`` on ``Im(u) = -1``."""
    v = np.atleast_1d(np.asarray(v, float))
    kernel = np.exp(1j * np.outer(v, np.asarray(k, float))) * trapezoid_weights(k)
    return kernel * (1j * v * (1.0 + 1j * v))[:, None]


def nyquist_vmax(k, safety=2.5):
    """Smallest ``v_max`` making :func:`cf_operator` full rank on this grid.

    Set by the *finest* strike spacing, not the k-span: two adjacent strikes are
    distinguishable only at frequencies that resolve their separation.
    """
    return float(safety * np.pi / np.min(np.diff(np.sort(np.asarray(k, float)))))


def cf_from_otm(k, z, v):
    """Characteristic function on ``Im(u) = -1`` implied by OTM prices."""
    v = np.atleast_1d(np.asarray(v, float))
    zeta = np.trapezoid(np.exp(1j * np.outer(v, k)) * z, k, axis=1)
    return 1.0 + 1j * v * (1.0 + 1j * v) * zeta


def model_cf(kind, params, tau, v):
    """Model CF of the *martingale* log return, evaluated at ``u = v - i``."""
    u = np.atleast_1d(np.asarray(v, float)) - 1j
    if kind == "vg":
        vg = VGParams(*params)
        raw = lambda w: vg_cf(w, tau, vg)
    else:
        s0, n0, t0, s1, n1, t1, l01, l10, p0 = params
        raw = lambda w: markov_vg_cf(w, tau, VGParams(s0, n0, t0),
                                     VGParams(s1, n1, t1), l01, l10, p0)
    compensator = np.log(raw(np.array([-1j]))[0])
    return np.exp(-1j * u * compensator) * raw(u)


# --------------------------------------------------------------------------
# The quote box, exactly, in CF space
# --------------------------------------------------------------------------
def cf_zonotope(k, z_bid, z_ask, v):
    """Centre and complex generators of the CF quote region per frequency.

    The attainable set at frequency ``i`` is exactly
    ``centre[i] + sum_j t_j gens[i, j]`` for ``t_j in [-1, 1]``.
    """
    v = np.atleast_1d(np.asarray(v, float))
    lift = cf_operator(k, v)
    centre = 1.0 + lift @ (0.5 * (np.asarray(z_bid) + np.asarray(z_ask)))
    gens = lift * (0.5 * (np.asarray(z_ask) - np.asarray(z_bid)))
    return centre, gens


def zonotope_support(centre, gens, theta):
    """Support function of the zonotope in direction ``theta``."""
    e = np.exp(-1j * theta)
    return np.real(e * centre) + np.abs(np.real(e[..., None] * gens)).sum(axis=-1)


def _directions(n_dir):
    return np.linspace(0.0, 2.0 * np.pi, int(n_dir), endpoint=False)


def zonotope_radius(centre, gens, n_dir=64):
    """Mean support radius: the natural scale to normalize an excess by."""
    r = np.stack([
        zonotope_support(centre, gens, np.full(centre.shape, t))
        - np.real(np.exp(-1j * t) * centre)
        for t in _directions(n_dir)
    ], axis=1)
    return r.mean(axis=1)


def zonotope_excess(phi, centre, gens, n_dir=64):
    """Distance by which ``phi`` protrudes from the zonotope, per frequency.

    Zero inside. Outside, the maximum over directions of (projection - support)
    is an exact lower bound on the Euclidean distance to the set, converging to
    it as ``n_dir`` grows.
    """
    theta = _directions(n_dir)
    proj = np.real(np.exp(-1j * theta)[None, :] * np.asarray(phi)[:, None])
    h = np.stack([zonotope_support(centre, gens, np.full(centre.shape, t))
                  for t in theta], axis=1)
    return np.maximum(proj - h, 0.0).max(axis=1)


def cf_band_loss(phi, centre, gens, weights=None, n_dir=64, eps=1e-12):
    """Zero inside the CF quote region; squared normalized excess outside.

    The direct analogue of the implied-volatility band loss, and exactly
    consistent with it on a Nyquist-complete grid -- but with no inversion
    step, hence no uninvertible-price case and no fallback penalty to exploit.
    """
    d = zonotope_excess(phi, centre, gens, n_dir)
    scale = np.maximum(zonotope_radius(centre, gens, n_dir), eps)
    per_v = (d / scale) ** 2
    if weights is None:
        return float(per_v.mean()), per_v
    weights = np.asarray(weights, float)
    return float((weights * per_v).sum() / weights.sum()), per_v


class CFBand:
    """Pre-compiled CF quote region for one chain: the calibration-loop object.

    The zonotope depends only on the quotes, so its support table can be built
    once and reused for every objective evaluation. That matters: recomputing
    the support per evaluation costs ~48 ms on a 201-strike chain at the
    Nyquist grid, against ~9 ms here -- the difference between the CF objective
    being five times dearer than the implied-volatility one and being its peer.
    Results are bit-identical to :func:`cf_band_loss`.
    """

    def __init__(self, k, z_bid, z_ask, v=None, n_dir=64, eps=1e-12):
        k = np.asarray(k, float)
        z_bid, z_ask = np.asarray(z_bid, float), np.asarray(z_ask, float)
        lo, hi = np.minimum(z_bid, z_ask), np.maximum(z_bid, z_ask)
        if v is None:
            v = np.linspace(0.0, nyquist_vmax(k), 2 * len(k))
        self.k, self.v = k, np.asarray(v, float)
        self.operator = cf_operator(k, self.v)
        self.centre, self.gens = cf_zonotope(k, lo, hi, self.v)
        theta = _directions(n_dir)
        self._cos, self._sin = np.cos(theta), np.sin(theta)
        self._support = np.stack(
            [zonotope_support(self.centre, self.gens, np.full(self.centre.shape, t))
             for t in theta], axis=1)
        self._radius = np.maximum(zonotope_radius(self.centre, self.gens, n_dir), eps)

    def cf_of_prices(self, z_model):
        """Model OTM prices on this chain's strikes -> CF on ``Im(u) = -1``."""
        return 1.0 + self.operator @ np.asarray(z_model, float)

    def excess(self, phi):
        """Per-frequency protrusion of ``phi`` from the quote region."""
        phi = np.asarray(phi)
        proj = np.real(phi)[:, None] * self._cos + np.imag(phi)[:, None] * self._sin
        return np.maximum(proj - self._support, 0.0).max(axis=1)

    def loss(self, phi):
        """Zero inside the quote region; mean squared normalized excess outside."""
        return float(np.mean((self.excess(phi) / self._radius) ** 2))

    def fraction_inside(self, phi):
        """Share of frequencies at which the model is inside the quoted market."""
        return float((self.excess(phi) == 0).mean())

    def loss_from_prices(self, prices, strikes, D_hat, A_hat, F_hat, guard=1e12):
        """CF band loss from model call prices, with the no-arbitrage cone enforced.

        The guard is not optional, and the reason is a real asymmetry between
        the two objectives. Both share an exact zero set, but only the
        implied-volatility loss enforces ``(A - D K)_+ <= C <= A`` *implicitly*:
        a price outside that range admits no implied volatility and collects the
        uninvertible penalty. The CF loss has no inversion step and so no such
        reflex -- a wing price below intrinsic is a tiny absolute displacement
        and barely registers.

        Left unguarded on the 2026-08-10 chain, the CF-fitted VG scores CF 0.122
        against the IV-fitted VG's 7.42, while its implied-volatility loss is
        1213.8 against 10.06. Restricted to the strikes where both objectives
        are defined it scores 22.5: the whole 54x gap was 24 strikes with no
        implied volatility.

        The tolerance must be relative to intrinsic, not to ``A``. Carr-Madan
        interpolates in log-moneyness, so deep-ITM prices carry a few cents of
        absolute error against the intrinsic floor -- 2.8 cents on a \\$2169
        option here, which an absolute ``1e-4 * A`` tolerance rightly admits and
        which is not an arbitrage. What that tolerance wrongly admits is the
        far wing, where intrinsic is zero and the model returns *negative*
        prices; those are caught by non-negativity instead.
        """
        prices = np.asarray(prices, float)
        strikes = np.asarray(strikes, float)
        if not np.all(np.isfinite(prices)) or np.any(prices < 0.0):
            return float(guard)
        lower = np.maximum(A_hat - D_hat * strikes, 0.0)
        tol = np.maximum(1e-5 * lower, 1e-8 * A_hat)
        if np.any(prices < lower - tol) or np.any(prices > A_hat * (1.0 + 1e-8)):
            return float(guard)
        put = prices - A_hat + D_hat * strikes
        z = np.where(strikes >= F_hat, prices, put) / (D_hat * F_hat)
        return self.loss(self.cf_of_prices(z))


